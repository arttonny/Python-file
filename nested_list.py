#there also exists nested lists.
#a nested list is a list inside a list
list1 = [1, 7, 4, 82, 85, 8, 3, 25, [68, 5, 54], 14, 23]
print (list1)
#to access a specific element in the list
print(list1[5])
print(list1[8])
#to access a specific element of a list inside a list we use double indexing
print(list1[8][1])
